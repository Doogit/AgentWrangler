import { linkSessions } from "../../src/outcomes/linker.js";
import { syncAllWorkspaces } from "../../src/outcomes/sync.js";
import { createFixtureDb, createInMemoryFixtureDb } from "../fixtures/seed.js";
import { GhWorld, type WorldPR, mergedPR, openPR, ts } from "./gh-world.js";
import {
  OWNER,
  REPO,
  T1,
  T2,
  advanceWorldToPass2,
  buildWorldPass1,
  mapWorkspace,
  seedSessions,
  snapshotRows,
} from "./s3-scenario.js";

const TRAILER = "Claude-Session: https://claude.ai/code/session_sess-a1";

/** Captured once from the pre-S3 REST path (see s3-scenario.ts); never regenerated by S3 code. */
const golden = JSON.parse(
  fs.readFileSync(new URL("./s3-golden.json", import.meta.url), "utf8"),
) as { pass1: unknown; pass2: unknown };

let db: Database.Database;

async function runPass(
  handle: Database.Database,
  world: GhWorld,
  at: string,
): Promise<{ failedStages: string[] }> {
  vi.setSystemTime(new Date(at));
  const runner = createOutcomesPassRunner({
    db: handle,
    probe: () => {},
    readToken: async () => ({ ok: true, data: "tok" }),
    createClient: (token) => new GhCliClient(token, world.runner()),
    sync: syncAllWorkspaces,
    link: linkSessions,
    derive: () => {},
    findings: extractAllFindings,
    deadlineMs: 60_000,
  });
  await runner.run();
  return { failedStages: runner.snapshot().failedStages };
}

function checksOf(handle: Database.Database, n: number): string | null | undefined {
  return (
    handle.prepare("SELECT checks_conclusion FROM work_items WHERE number = ?").get(n) as
      | { checks_conclusion: string | null }
      | undefined
  )?.checks_conclusion;
}

/** Drop every row keyed to the scenario's PRs #6 and #7 (open in pass 1). */
function withoutOpenPRs(snapshot: unknown): unknown {
  const s = snapshot as Record<string, Array<{ work_item_id: string }>>;
  return Object.fromEntries(
    Object.entries(s).map(([table, rows]) => [
      table,
      rows.filter((r) => !/#[67]$/.test(r.work_item_id)),
    ]),
  );
}

function count(handle: Database.Database, table: string): number {
  return (handle.prepare(`SELECT COUNT(*) AS n FROM ${table}`).get() as { n: number }).n;
}

function linkRows(handle: Database.Database): unknown[] {
  return handle
    .prepare(
      "SELECT session_id, work_item_id, method FROM session_work_links ORDER BY session_id, work_item_id",
    )
    .all();
}

/**
 * 120 merged PRs + 2 open PRs, every rollup SUCCESS. sess-a1's trailer is in
 * #30 and sess-a3 links to #25 by reverse lookup: both are inside the REST
 * listing's 100-PR window but OFF a warm pass's first GraphQL page.
 */
function scaleWorld(): GhWorld {
  const world = new GhWorld();
  const repo = world.repo(OWNER, REPO);
  repo.commitPulls = new Map([["orphan-sha", [25]]]);
  for (let i = 1; i <= 120; i++) {
    repo.prs.push(
      mergedPR(
        i,
        ts(i),
        i === 30 ? { commits: [{ sha: "c-30-0", message: `x\n\n${TRAILER}` }] } : {},
      ),
    );
  }
  repo.prs.push(openPR(121, ts(121)), openPR(122, ts(2)));
  return world;
}

beforeEach(() => {
  vi.useFakeTimers({ toFake: ["Date"] });
  db = createInMemoryFixtureDb();
  mapWorkspace(db);
  seedSessions(db);
});

afterEach(() => {
  db.close();
  vi.useRealTimers();
});

describe("P0-U13 S3 — batched GraphQL PR reads", () => {
  it("(a) a warm pass makes 1 GraphQL page call for the repo and zero per-PR reads (linker + reverse lookup included)", async () => {
    const world = scaleWorld();
    expect((await runPass(db, world, T1)).failedStages).toEqual([]);
    const linksAfterCold = linkRows(db);
    expect(linksAfterCold).toContainEqual({
      session_id: "sess-a1",
      work_item_id: "gh:acme/repo-alpha#30",
      method: "TRAILER",
    });
    expect(linksAfterCold).toContainEqual({
      session_id: "sess-a3",
      work_item_id: "gh:acme/repo-alpha#25",
      method: "SHA_OVERLAP",
    });

    world.reset();
    expect((await runPass(db, world, T2)).failedStages).toEqual([]);
    expect(world.counts.graphqlPage).toBe(1);
    expect(world.counts.listPRs).toBe(0);
    expect(world.counts).toMatchObject({
      getCheckConclusion: 0,
      listPRCommits: 0,
      getPRBody: 0,
      getPRDiff: 0,
      listPullsForCommit: 0,
      getReviewThreads: 0,
    });
    expect(linkRows(db)).toEqual(linksAfterCold);
  });

  it("(b) a cold backfill makes ceil(PRs/50) page calls and per-PR check reads only for non-SUCCESS/non-null rollups", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    const odd: Record<number, Partial<WorldPR>> = {
      10: { rollup: "FAILURE", checks: "FAILURE" },
      20: { rollup: "FAILURE", checks: "FAILURE" },
      30: { rollup: "ERROR", checks: "FAILURE" },
      40: { rollup: "PENDING", checks: "PENDING" },
      50: { rollup: null, checks: "NONE" },
    };
    for (let i = 1; i <= 120; i++) repo.prs.push(mergedPR(i, ts(i), odd[i] ?? {}));

    expect((await runPass(db, world, T1)).failedStages).toEqual([]);
    expect(world.counts.graphqlPage).toBe(3);
    expect(world.counts.listPRs).toBe(0);
    const checkRefs = world.log
      .filter((l) => l.kind === "getCheckConclusion")
      .map((l) => l.ref)
      .sort();
    expect(checkRefs).toEqual(["head-10", "head-20", "head-30", "head-40"]);
    expect(world.counts).toMatchObject({ listPRCommits: 0, getPRBody: 0, getReviewThreads: 0 });
    expect(count(db, "work_items")).toBe(120);
    expect(checksOf(db, 10)).toBe("FAILURE");
    expect(checksOf(db, 40)).toBe("PENDING");
    expect(checksOf(db, 50)).toBe("NONE");
    expect(checksOf(db, 51)).toBe("SUCCESS");
  });

  it("(b2) a page that hits the stdout cap is retried at 25 and still lands every row", async () => {
    const world = new GhWorld();
    world.maxPageSizeBeforeStdoutLimit = 25;
    const repo = world.repo(OWNER, REPO);
    for (let i = 1; i <= 30; i++) repo.prs.push(mergedPR(i, ts(i)));
    expect((await runPass(db, world, T1)).failedStages).toEqual([]);
    expect(world.pageSizes).toContain(25);
    expect(count(db, "work_items")).toBe(30);
  });

  it("(c) E3 reads each newly merged PR's diff exactly once, never again for that PR", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    for (let i = 1; i <= 5; i++) repo.prs.push(mergedPR(i, ts(i)));
    await runPass(db, world, T1);
    const diffRefs = () =>
      world.log
        .filter((l) => l.kind === "getPRDiff")
        .map((l) => l.ref)
        .sort();
    expect(diffRefs()).toEqual(["1", "2", "3", "4", "5"]);

    // #2 gets a post-merge comment (updatedAt moves); #6 is newly merged.
    world.reset();
    const pr2 = repo.prs.find((p) => p.number === 2) as WorldPR;
    pr2.updatedAt = ts(50);
    repo.prs.push(mergedPR(6, ts(51)));
    await runPass(db, world, T2);
    expect(diffRefs()).toEqual(["6"]);

    world.reset();
    await runPass(db, world, "2026-09-01T00:20:00.000Z");
    expect(diffRefs()).toEqual([]);
  });

  it("(d) terminal PRs with a stored non-terminal conclusion re-resolve every pass inside the one page call", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    for (let i = 1; i <= 60; i++) repo.prs.push(mergedPR(i, ts(100 + i)));
    // Oldest updatedAt → off the first page on a warm pass.
    repo.prs.push(mergedPR(201, ts(1), { rollup: "PENDING", checks: "PENDING" }));
    await runPass(db, world, T1);
    expect(checksOf(db, 201)).toBe("PENDING");

    // Checks complete WITHOUT bumping the PR's updatedAt.
    Object.assign(repo.prs.find((p) => p.number === 201) as WorldPR, {
      rollup: "SUCCESS",
      checks: "SUCCESS",
    });
    world.reset();
    await runPass(db, world, T2);
    expect(world.counts.graphqlPage).toBe(1);
    expect(world.counts.getCheckConclusion).toBe(0);
    expect(checksOf(db, 201)).toBe("SUCCESS");
  });

  it("(d2) operator decision 2026-09-28: the page query requests only MERGED and CLOSED PRs, so no OPEN row is ever written", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    repo.prs.push(mergedPR(1, ts(1)), openPR(2, ts(2)), openPR(3, ts(3)));
    expect((await runPass(db, world, T1)).failedStages).toEqual([]);
    expect(world.queries.length).toBeGreaterThan(0);
    for (const q of world.queries) {
      expect(q).toMatch(/states:\s*\[MERGED,\s*CLOSED\]/);
      expect(q).not.toMatch(/OPEN/);
      expect(q).not.toMatch(/\bopen:/);
    }
    expect(db.prepare("SELECT number, state FROM work_items ORDER BY number").all()).toEqual([
      { number: 1, state: "MERGED" },
    ]);
  });

  it("(e) a FORBIDDEN rollup skips the row and holds the watermark, like the pre-S3 403 path (never a false OBSERVED_SUCCESS)", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    repo.checksForbidden = true;
    repo.prs.push(mergedPR(1, ts(1)), mergedPR(2, ts(2), { rollup: "FAILURE", checks: "FAILURE" }));
    await runPass(db, world, T1);
    expect(world.counts.getCheckConclusion).toBe(0);
    expect(count(db, "work_items")).toBe(0);
    expect(count(db, "work_item_branch_keys")).toBe(0);
    expect(
      db.prepare("SELECT 1 FROM user_config WHERE key = 'gh_watermark:acme/repo-alpha'").get(),
    ).toBeUndefined();

    world.reset();
    await runPass(db, world, T2);
    expect(world.counts.graphqlPage).toBe(1);
    expect(world.counts.getCheckConclusion).toBe(0);
    expect(count(db, "work_items")).toBe(0);
  });

  it("(e1) an all-FORBIDDEN repo (watermark never advances) pages at most the pre-S3 100-PR window per pass", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    repo.checksForbidden = true;
    for (let i = 1; i <= 120; i++) repo.prs.push(mergedPR(i, ts(i)));
    for (const at of [T1, T2, T2]) {
      world.reset();
      await runPass(db, world, at);
      expect(world.counts.graphqlPage).toBe(2);
      expect(world.counts.getCheckConclusion).toBe(0);
    }
    expect(count(db, "work_items")).toBe(0);
  });

  it("(e2) FORBIDDEN is per PR: a readable rollup on the same page still lands, the forbidden PR does not", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    repo.forbiddenPRs = new Set([2]);
    repo.prs.push(
      mergedPR(1, ts(1)),
      mergedPR(2, ts(2)),
      mergedPR(3, ts(3), { rollup: null, checks: "NONE" }),
    );
    await runPass(db, world, T1);
    expect(world.counts.getCheckConclusion).toBe(0);
    expect(
      db.prepare("SELECT number, checks_conclusion FROM work_items ORDER BY number").all(),
    ).toEqual([
      { number: 1, checks_conclusion: "SUCCESS" },
      { number: 3, checks_conclusion: "NONE" },
    ]);
    expect(
      db.prepare("SELECT 1 FROM user_config WHERE key = 'gh_watermark:acme/repo-alpha'").get(),
    ).toBeUndefined();
  });

  it("(e3) a new head SHA whose rollup is forbidden cannot inherit the old head's stored checks", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    repo.prs.push(mergedPR(1, ts(1)));
    await runPass(db, world, T1);
    expect(checksOf(db, 1)).toBe("SUCCESS");

    Object.assign(repo.prs[0] as WorldPR, {
      headSha: "head-1b",
      mergeCommitSha: "merge-1b",
      updatedAt: ts(50),
    });
    repo.forbiddenPRs = new Set([1]);
    world.reset();
    await runPass(db, world, T2);
    // Row untouched: not re-projected with the new head under the old conclusion.
    expect(
      db.prepare("SELECT final_commit, checks_conclusion FROM work_items WHERE number = 1").get(),
    ).toEqual({ final_commit: "merge-1", checks_conclusion: "SUCCESS" });
    expect(
      (
        db
          .prepare("SELECT value FROM user_config WHERE key = 'gh_watermark:acme/repo-alpha'")
          .get() as { value: string }
      ).value,
    ).toBe(ts(1));
  });

  it("(b3) a stdout-limit retry drops the by-number aliases and reads at 25", async () => {
    const world = new GhWorld();
    world.maxPageSizeBeforeStdoutLimit = 25;
    const repo = world.repo(OWNER, REPO);
    for (let i = 1; i <= 30; i++) repo.prs.push(mergedPR(i, ts(100 + i)));
    repo.prs.push(mergedPR(201, ts(1), { rollup: "PENDING", checks: "PENDING" }));
    await runPass(db, world, T1);
    world.reset();
    Object.assign(repo.prs.find((p) => p.number === 201) as WorldPR, {
      rollup: "SUCCESS",
      checks: "SUCCESS",
    });
    await runPass(db, world, T2);
    expect(world.pageSizes).toEqual([50, 25]);
    expect(world.queries[0]).toMatch(/n201: pullRequest/);
    expect(world.queries[1]).not.toMatch(/pullRequest\(number/);
  });

  it("(f) work_items, branch keys, links and findings equal the pre-S3 REST path's rows over two passes", async () => {
    const world = buildWorldPass1();
    await runPass(db, world, T1);
    expect(world.counts.graphqlPage).toBeGreaterThan(0);
    expect(world.counts.listPRs).toBe(0);
    // The golden was captured with OPEN PRs #6/#7 synced. Since the 2026-09-28
    // operator decision OPEN PRs are never requested, so their rows (and the
    // rows derived from them) are excluded from both sides; every row of the
    // other PRs is per-work-item independent and must still equal the REST rows.
    expect(withoutOpenPRs(snapshotRows(db))).toEqual(withoutOpenPRs(golden.pass1));

    world.reset();
    advanceWorldToPass2(world);
    await runPass(db, world, T2);
    expect(world.counts.listPRs).toBe(0);
    expect(withoutOpenPRs(snapshotRows(db))).toEqual(withoutOpenPRs(golden.pass2));
    // #6 merged: it lands as terminal on the first pass that sees it; #7 is still open: never seen.
    expect(
      db
        .prepare("SELECT number, state, checks_conclusion FROM work_items WHERE number IN (6, 7)")
        .all(),
    ).toEqual([{ number: 6, state: "MERGED", checks_conclusion: "SUCCESS" }]);
  });

  it("(g) with no in-memory linker cache, a warm pass on a reopened DB still makes zero per-PR reads", async () => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), "aw-s3-"));
    const file = path.join(dir, "db.sqlite");
    const first = createFixtureDb(file);
    mapWorkspace(first);
    seedSessions(first);
    const world = scaleWorld();
    try {
      await runPass(first, world, T1);
      const links = linkRows(first);
      first.close();

      const second = openDb(file);
      try {
        world.reset();
        await runPass(second, world, T2);
        expect(world.counts.graphqlPage).toBe(1);
        expect(world.perPrReads()).toBe(0);
        expect(linkRows(second)).toEqual(links);
      } finally {
        second.close();
      }
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });

  it("a PR with more than 100 review threads falls back to the paginated per-PR thread read", async () => {
    const world = new GhWorld();
    const repo = world.repo(OWNER, REPO);
    const threads = Array.from({ length: 101 }, (_, i) => ({ id: `t-${i}`, isResolved: true }));
    repo.prs.push(mergedPR(1, ts(1), { threads }), mergedPR(2, ts(2)));
    await runPass(db, world, T1);
    expect(world.log.filter((l) => l.kind === "getReviewThreads").map((l) => l.ref)).toEqual(["1"]);
    expect(count(db, "review_findings")).toBe(101);
  });

  it("a failed page read writes nothing for the repo and keeps the watermark retryable", async () => {
    const world = new GhWorld();
    world.repo(OWNER, REPO).prs.push(mergedPR(1, ts(1)));
    // Cold pass on a repo name the world does not serve → GraphQL NOT_FOUND on `repository`.
    db.prepare(
      "UPDATE workspaces SET repo_name='repo-missing' WHERE workspace_id='ws-alpha'",
    ).run();
    const { failedStages } = await runPass(db, world, T1);
    expect(failedStages).toContain("sync");
    expect(count(db, "work_items")).toBe(0);
    expect(
      db.prepare("SELECT 1 FROM user_config WHERE key = 'gh_watermark:acme/repo-missing'").get(),
    ).toBeUndefined();
  });
});
