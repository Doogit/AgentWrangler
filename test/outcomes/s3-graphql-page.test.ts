/**
 * test/outcomes/s3-graphql-page.test.ts — P0-U13 S3: batched GraphQL PR reads.
 *
 * Every pass runs the production composition (createOutcomesPassRunner with
 * the real sync → link → findings stages and a real GhCliClient) against a fake
 * `gh` runner that serves one synthetic GitHub state over both REST and
 * GraphQL and COUNTS each read (gh-world.ts).
 *
 * Independent oracles:
 *   - call counts derive from the injected world (PR counts, rollup states),
 *     not from the code's own counters;
 *   - row equivalence compares against s3-golden.json, captured by running the
 *     PRE-S3 REST code (47751fde) on the same scenario before any S3 change.
 * Synthetic owner/repo only.
 */

